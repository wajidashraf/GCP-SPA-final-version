import { randomUUID } from 'node:crypto';
import { DataverseError, dataverseUrl, dvPostRaw } from './dataverseClient.js';

export interface ChangeSetOperation {
  method: 'PATCH';
  path: string;
  headers: Record<string, string>;
  body: Record<string, unknown>;
}

export class DataverseBatchError extends DataverseError {
  constructor(message: string, status: number, public uncertain = false) {
    super(message, status);
    this.name = 'DataverseBatchError';
  }
}

/** A single atomic transaction. Conditional headers belong to each operation. */
export const buildChangeSet = (
  operations: readonly ChangeSetOperation[],
  apiBaseUrl: string,
): { contentType: string; body: string } => {
  if (!operations.length) throw new Error('An empty Dataverse changeset is not allowed');
  const boundary = `batch_${randomUUID()}`;
  const change = `changeset_${randomUUID()}`;
  const lines = [`--${boundary}`, `Content-Type: multipart/mixed; boundary=${change}`, ''];
  for (const [index, operation] of operations.entries()) {
    // Paths and headers are generated by the server, never passed through from
    // the caller. Reject newline/path injection here as a second boundary.
    if (!/^[a-z][a-z0-9_]*\([0-9a-f-]{36}\)$/i.test(operation.path)) {
      throw new Error('Invalid changeset record path');
    }
    lines.push(`--${change}`, 'Content-Type: application/http',
      'Content-Transfer-Encoding: binary', `Content-ID: ${index + 1}`, '',
      `${operation.method} ${apiBaseUrl.replace(/\/+$/, '')}/${operation.path} HTTP/1.1`,
      'Content-Type: application/json', 'Accept: application/json',
      'OData-Version: 4.0', 'OData-MaxVersion: 4.0');
    for (const [name, value] of Object.entries(operation.headers)) {
      if (!['If-Match', 'If-None-Match'].includes(name) || /[\r\n]/.test(value)) {
        throw new Error('Invalid changeset conditional header');
      }
      lines.push(`${name}: ${value}`);
    }
    lines.push('', JSON.stringify(operation.body));
  }
  lines.push(`--${change}--`, `--${boundary}--`, '');
  return { contentType: `multipart/mixed; boundary=${boundary}`, body: lines.join('\r\n') };
};

const malformed = (): never => {
  throw new DataverseBatchError('Dataverse returned an incomplete transaction response', 502, true);
};
const splitHeaders = (value: string): { headers: Map<string, string>; body: string } => {
  const at = value.indexOf('\n\n');
  if (at < 0) return malformed();
  const headers = new Map<string, string>();
  for (const line of value.slice(0, at).split('\n')) {
    const colon = line.indexOf(':');
    if (colon <= 0) return malformed();
    const key = line.slice(0, colon).trim().toLowerCase();
    if (headers.has(key)) return malformed();
    headers.set(key, line.slice(colon + 1).trim());
  }
  return { headers, body: value.slice(at + 2) };
};
interface OperationResponse { status: number; contentId?: string }
const readMultipart = (contentType: string, raw: string, depth = 0): OperationResponse[] => {
  if (depth > 1 || !/^multipart\/mixed\s*;/i.test(contentType)) return malformed();
  const boundaryMatch = /(?:^|;)\s*boundary=(?:"([^"\r\n]+)"|([^;\s]+))/i.exec(contentType);
  const boundary = boundaryMatch?.[1] ?? boundaryMatch?.[2];
  if (!boundary || boundary.length > 200) return malformed();
  const text = raw.replace(/\r\n/g, '\n');
  const marker = `--${boundary}`;
  const lines = text.split('\n');
  const boundaries = lines.flatMap((line, index) => line === marker || line === `${marker}--` ? [index] : []);
  if (boundaries.length < 2 || boundaries[0] !== 0 || lines[boundaries.at(-1)!] !== `${marker}--`) return malformed();
  if (lines.slice(boundaries.at(-1)! + 1).some((line) => line.trim())) return malformed();
  const responses: OperationResponse[] = [];
  for (let index = 0; index < boundaries.length - 1; index++) {
    const start = boundaries[index];
    if (lines[start] !== marker) return malformed();
    const part = splitHeaders(lines.slice(start + 1, boundaries[index + 1]).join('\n'));
    const type = part.headers.get('content-type') ?? '';
    if (/^multipart\/mixed\s*;/i.test(type)) {
      if (depth !== 0 || boundaries.length !== 2) return malformed();
      responses.push(...readMultipart(type, part.body.replace(/\n$/, ''), depth + 1));
    } else {
      if (!/^application\/http(?:\s*;|$)/i.test(type)) return malformed();
      const firstLineEnd = part.body.indexOf('\n');
      const status = /^HTTP\/1\.[01] (\d{3})(?: .*)?$/.exec(part.body.slice(0, firstLineEnd));
      if (!status) return malformed();
      // Validate the embedded HTTP header block as well as its status line.
      splitHeaders(part.body.slice(firstLineEnd + 1));
      const numeric = Number(status[1]);
      if (depth === 0 && numeric < 400) return malformed();
      responses.push({ status: numeric, contentId: part.headers.get('content-id') });
    }
  }
  return responses;
};

/** The outer batch's 200 does not imply that its transaction committed. */
export const validateChangeSetResponse = (contentType: string, body: string, expectedCount: number): void => {
  const responses = readMultipart(contentType, body);
  const failure = responses.find((response) => response.status >= 400);
  if (failure) throw new DataverseBatchError('Dataverse rejected a booking transaction operation', failure.status);
  if (responses.length !== expectedCount || responses.some((r) => r.status < 200 || r.status >= 300)) return malformed();
  if (responses.some((r) => r.contentId !== undefined) &&
      responses.some((r, index) => r.contentId !== String(index + 1))) return malformed();
};

export const executeChangeSet = async (operations: readonly ChangeSetOperation[]): Promise<void> => {
  const built = buildChangeSet(operations, dataverseUrl(''));
  const response = await dvPostRaw('$batch', built.body, built.contentType);
  const body = await response.text();
  validateChangeSetResponse(response.headers.get('content-type') ?? '', body, operations.length);
};
