// Compile the frontend's canonical, data-only choice mirrors into this build.
// The API package remains deployable without access to files outside api/.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';

const choices = {};
for (const [file, exportsToInclude] of [
  ['engagementChoices.ts', ['engagementTypeChoices', 'ENGAGEMENT_TYPE_PHYSICAL', 'ENGAGEMENT_STATUS_CANCELLED', 'ENGAGEMENT_STATUS_SCHEDULED', 'ENGAGEMENT_STATUS_COMPLETED']],
  ['slotChoices.ts', ['SLOT_STATUS_AVAILABLE', 'SLOT_STATUS_BOOKED']],
  ['requestChoices.ts', ['requestStatusChoices']],
]) {
  const source = await readFile(new URL(`../../src/data/${file}`, import.meta.url), 'utf8');
  const compiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const sandbox = { exports: {} };
  runInNewContext(compiled, sandbox, { timeout: 1000 });
  for (const name of exportsToInclude) {
    if (sandbox.exports[name] === undefined) throw new Error(`Missing canonical booking choice ${name}`);
    choices[name] = sandbox.exports[name];
  }
}
const directory = new URL('../generated/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('bookingChoices.ts', directory),
  `// Generated by scripts/generateBookingChoices.mjs; edit src/data instead.\nexport const bookingChoices = ${JSON.stringify(choices, null, 2)} as const;\n`);
